import { randomUUID } from 'node:crypto';
import { Pool } from 'pg';
import { afterAll, describe, expect, it, vi } from 'vitest';
import { IdentityService } from '../../src/application/identity';
import type { Profile } from '../../src/domain/model';
import { failure, success } from '../../src/domain/result';
import { PostgresIdentityRepository } from '../../src/infrastructure/identity-repository';
import { secrets } from '../../src/infrastructure/secrets';
import { SupabasePostgresStore } from '../../src/infrastructure/supabase-postgres';
const connectionString=process.env.WORDPAIRS_TEST_DATABASE_URL;
if (!connectionString || new URL(connectionString).hostname!=='127.0.0.1') throw new Error('Disposable local database required');
const admin=new Pool({connectionString,ssl:false});
const pool=new Pool({connectionString,ssl:false,options:'-c role=service_role',max:3});
const repository=new PostgresIdentityRepository(pool);
let now=1000000;
const oidc={authorization:vi.fn(async()=>success('https://issuer.example.test/authorize')),verify:vi.fn(async()=>success({issuer:'https://issuer.example.test',subject:'PRIVATE-TEST-SUBJECT'}))};
const service=new IdentityService(repository,secrets,{next:()=>`identity-${randomUUID()}`},{integer:minimum=>minimum},{now:()=>now},oidc);
afterAll(async()=>{
  await admin.query(`delete from wordpairs.sessions where profile_id like 'identity-%'; delete from wordpairs.guest_credentials where profile_id like 'identity-%'; delete from wordpairs.profile_roles where profile_id like 'identity-%'; delete from wordpairs.idempotency_records where aggregate_kind='profile' and aggregate_id like 'identity-%'; delete from wordpairs.outbox_events where aggregate_kind='profile' and aggregate_id like 'identity-%'; delete from wordpairs.aggregates where kind='profile' and id like 'identity-%'; delete from wordpairs.profiles where id like 'identity-%';`);
  await pool.end();await admin.end();
});
describe('TR identity/session persistence through actual service-role RPCs',()=>{
  it('restores a browser guest after session expiry, isolates a cleared browser, and serializes concurrent first entry',async()=>{
    const credential=secrets.token();
    const entries=await Promise.all([service.guest(credential),service.guest(credential)]);
    if (!entries[0].ok||!entries[1].ok) throw new Error('Guest failed');
    expect(entries[0].value.profile.id).toBe(entries[1].value.profile.id);
    expect(entries[0].value.profile.publicLeaderboard).toBe(false);
    now+=31*86400000;
    expect(await service.session(entries[0].value.sessionToken)).toEqual(failure('NOT_AUTHENTICATED'));
    const restored=await service.guest(credential);
    const cleared=await service.guest(null);
    if (!restored.ok||!cleared.ok) throw new Error('Restore failed');
    expect(restored.value.profile.id).toBe(entries[0].value.profile.id);
    expect(cleared.value.profile.id).not.toBe(restored.value.profile.id);
    expect((await admin.query("select count(*)::int as count from wordpairs.guest_credentials where credential_hash=$1",[secrets.hash(credential)])).rows[0].count).toBe(1);
    expect((await admin.query("select count(*)::int as count from wordpairs.sessions where token_digest=$1",[restored.value.sessionToken])).rows[0].count).toBe(0);
  });
  it('persists icon/opt-in/generated alias using the canonical command transaction, then replays and rejects conflicts',async()=>{
    const entry=await service.guest(null);
    if (!entry.ok) throw new Error('Guest failed');
    const id=entry.value.profile.id;
    const actor={profileId:id,roles:['player'] as const};
    const command={aggregateId:id,actorId:id,commandId:'profile-settings',requestDigest:'settings-digest',expectedVersion:0};
    const store=new SupabasePostgresStore<Profile>(pool,'profile');
    const changed=await service.preferences(command,actor,{icon:'fox',publicLeaderboard:true,regenerateAlias:true},store);
    expect(changed.ok && changed.value.icon).toBe('fox');
    expect(changed.ok && changed.value.alias).not.toBe(entry.value.profile.alias);
    expect(await service.preferences(command,actor,{icon:'fox',publicLeaderboard:true,regenerateAlias:true},store)).toEqual(changed);
    expect(await service.preferences({...command,requestDigest:'other'},actor,{icon:'owl'},store)).toEqual(failure('IDEMPOTENCY_CONFLICT'));
    const restored=await service.guest(entry.value.guestCredential);
    expect(restored.ok && restored.value.profile.icon).toBe('fox');
    expect((await admin.query('select icon,public_leaderboard from wordpairs.profiles where id=$1',[id])).rows[0]).toEqual({icon:'fox',public_leaderboard:true});
    await service.logout(entry.value.sessionToken);
    expect(await service.session(entry.value.sessionToken)).toEqual(failure('NOT_AUTHENTICATED'));
  });
  it('consumes browser-bound OIDC state once, associates only verified issuer/subject and never links the guest',async()=>{
    const guest=await service.guest(null);
    const begin=await service.beginLogin();
    if (!begin.ok || !guest.ok) throw new Error('Setup failed');
    const login=await service.completeLogin(begin.value.browserToken,'code','state');
    if (!login.ok) throw new Error('Login failed');
    expect(login.value.profile.kind).toBe('member');
    expect(login.value.profile.id).not.toBe(guest.value.profile.id);
    expect(login.value.profile.publicLeaderboard).toBe(true);
    expect(JSON.stringify(login)).not.toContain('PRIVATE-TEST-SUBJECT');
    expect(await service.completeLogin(begin.value.browserToken,'code','state')).toEqual(failure('NOT_AUTHENTICATED'));
    const again=await service.beginLogin();
    if (!again.ok) throw new Error('Setup failed');
    const same=await service.completeLogin(again.value.browserToken,'code','state');
    expect(same.ok && same.value.profile.id).toBe(login.value.profile.id);
    const restored=await service.guest(guest.value.guestCredential);
    expect(restored.ok && restored.value.profile.id).toBe(guest.value.profile.id);
    await admin.query("insert into wordpairs.profile_roles values($1,'moderator')",[login.value.profile.id]);
    const resolved=await service.session(login.value.sessionToken);
    expect(resolved.ok && resolved.value.actor.roles).toEqual(['player','moderator']);
    const expires=await service.beginLogin();
    if (!expires.ok) throw new Error('Setup failed');
    now+=600001;
    expect(await service.completeLogin(expires.value.browserToken,'code','state')).toEqual(failure('NOT_AUTHENTICATED'));
  });
  it('does not establish a member when the provider rejects the token',async()=>{
    const count=await admin.query("select count(*)::int as count from wordpairs.profiles where identity_kind='member'");
    oidc.verify.mockResolvedValueOnce(failure('NOT_AUTHENTICATED'));
    const begin=await service.beginLogin();
    if (!begin.ok) throw new Error('Setup failed');
    expect(await service.completeLogin(begin.value.browserToken,'code','state')).toEqual(failure('NOT_AUTHENTICATED'));
    expect((await admin.query("select count(*)::int as count from wordpairs.profiles where identity_kind='member'")).rows).toEqual(count.rows);
    expect(await service.session('forged-token')).toEqual(failure('NOT_AUTHENTICATED'));
  });
});
