import {Pool} from 'pg';
import {afterAll,beforeAll,describe,expect,it} from 'vitest';
import {RoomService} from '../../src/application/rooms';
import {playerAuthority} from '../../src/domain/rooms';
import {PostgresRoomRepository} from '../../src/infrastructure/room-repository';
import {secrets,random} from '../../src/infrastructure/secrets';
const connectionString=process.env.WORDPAIRS_TEST_DATABASE_URL;
if(!connectionString||new URL(connectionString).hostname!=='127.0.0.1')throw new Error('Disposable local database required');
const admin=new Pool({connectionString,ssl:false});const pool=new Pool({connectionString,ssl:false,options:'-c role=service_role'});
const repository=new PostgresRoomRepository(pool);let event=0;const now=4000000;
const service=new RoomService(repository,{now:()=>now},{next:()=>`rooms-event-${++event}`},random);
const command=(roomId:string,actorId:string,commandId:string,expectedVersion=0)=>({aggregateId:roomId,actorId,commandId,expectedVersion,requestDigest:commandId});
beforeAll(async()=>{await admin.query("insert into wordpairs.profiles(id,identity_kind,alias,icon,public_leaderboard) values ('rooms-observer','guest','Guest Observer','fox',false),('rooms-observer2','guest','Guest Observer Two','owl',false)");});
afterAll(async()=>{
  await admin.query("delete from wordpairs.quick_assignments where command_id like 'rooms-%'; delete from wordpairs.room_invitations where room_id like 'rooms-%'; delete from wordpairs.idempotency_records where aggregate_kind='room' and aggregate_id like 'rooms-%'; delete from wordpairs.outbox_events where aggregate_kind='room' and aggregate_id like 'rooms-%'; delete from wordpairs.deadline_jobs where aggregate_kind='room' and aggregate_id like 'rooms-%'; delete from wordpairs.aggregates where kind='room' and id like 'rooms-%'; delete from wordpairs.room_members where room_id like 'rooms-%'; delete from wordpairs.rooms where id like 'rooms-%'; delete from wordpairs.profiles where id in ('rooms-observer','rooms-observer2');");
  await pool.end();await admin.end();
});
describe('TR-31 actual create/join/assignment transactions',()=>{
  it('creates private by default, returns canonical creation retry, and atomically claims only one final seat',async()=>{
    const create=command('rooms-private','p1','rooms-create');
    const initial=await service.create(create,2);
    if(!initial.ok)throw new Error(JSON.stringify(initial));
    expect(initial.value.code).toMatch(/^[0-9A-HJKMNP-TV-Z]{8}$/);
    expect(await service.create(create,2)).toEqual(initial);
    const loaded=await repository.get('rooms-private');if(!loaded.ok)throw new Error('Load failed');
    expect(loaded.value.discoverable).toBe(false);
    const commands=[command('rooms-private','p2','rooms-join2'),command('rooms-private','p3','rooms-join3')];
    const results=await Promise.all(commands.map(cmd=>service.join(cmd,'player',null)));
    expect(results.filter(result=>result.ok)).toHaveLength(1);
    expect(results.filter(result=>!result.ok).map(result=>!result.ok&&result.error.code)).toEqual(['CONFLICT']);
    const winner=results.findIndex(result=>result.ok);
    expect(await service.join(commands[winner],'player',null)).toEqual(results[winner]);
    const row=await admin.query("select count(*)::int as count from wordpairs.room_members where room_id='rooms-private' and membership_kind='player'");
    expect(row.rows[0].count).toBe(2);
    expect((await admin.query("select count(*)::int as count from wordpairs.outbox_events where aggregate_kind='room' and aggregate_id='rooms-private'")).rows[0].count).toBe(2);
    expect((await service.resolve('rooms-private','rooms-observer','session')).ok).toBe(false);
    const invitation=secrets.token();await repository.invite('rooms-private','p1',secrets.hash(invitation));
    const resolved=await service.resolve(initial.value.code,'rooms-observer','session',secrets.hash(invitation));
    if(!resolved.ok)throw new Error('Invitation failed');
    expect(resolved.value.inviterId).toBe('p1');
    expect(await service.resolve('WRONGREF','rooms-observer','session',secrets.hash(invitation))).toEqual({ok:false,error:{code:'NOT_FOUND'}});
    expect((await service.join(command('rooms-private','rooms-observer','rooms-observe',1),'observer',resolved.value.inviterId)).ok).toBe(true);
    const observed=await repository.get('rooms-private');if(!observed.ok)throw new Error('Load failed');
    expect(observed.value.players).toHaveLength(2);expect(observed.value.observers[0].followedPlayerId).toBe('p1');
    expect(await repository.invite('rooms-private','rooms-observer',secrets.hash('forged-observer-invitation'))).toEqual({ok:false,error:{code:'NOT_AUTHORIZED'}});
    expect(playerAuthority(observed.value,'rooms-observer')).toEqual({ok:false,error:{code:'NOT_AUTHORIZED'}});
    const view=await service.view(observed.value,'rooms-observer');
    expect(view.ok&&view.value.followedPlayerId).toBe('p1');
    expect(view.ok&&view.value.players[0].icon).toBe('owl');
    expect(JSON.stringify(view)).not.toContain(initial.value.code);
  });
  it('limits room-code attempts to ten per rolling minute and makes unknown and closed codes generic',async()=>{
    for(let attempt=0;attempt<10;attempt++)expect(await repository.lookupCode('ZZZZZZZZ','rooms-rate-session',now)).toEqual({ok:false,error:{code:'NOT_FOUND'}});
    expect(await repository.lookupCode('ZZZZZZZZ','rooms-rate-session',now+59999)).toEqual({ok:false,error:{code:'RATE_LIMITED'}});
    expect(await repository.lookupCode('ZZZZZZZZ','rooms-rate-session',now+60000)).toEqual({ok:false,error:{code:'NOT_FOUND'}});
  });
  it('selects the oldest eligible room with stable ID ties and keeps assignment/replay stable after other rooms become eligible',async()=>{
    expect((await service.create(command('rooms-b','p1','rooms-create-b'),2,true)).ok).toBe(true);
    expect((await service.create(command('rooms-a','p1','rooms-create-a'),2,true)).ok).toBe(true);
    const results=await Promise.all(['p2','p3'].map(actor=>service.quickMatch(actor,`rooms-quick-${actor}`,'quick-digest')));
    expect(results.filter(result=>result.ok)).toHaveLength(2);
    expect(results.map(result=>result.ok&&result.value.joined).sort()).toEqual(['rooms-a','rooms-b']);
    const winner=0;
    expect(await service.quickMatch(['p2','p3'][winner],`rooms-quick-${['p2','p3'][winner]}`,'quick-digest')).toEqual(results[winner]);
    expect(await service.quickMatch(['p2','p3'][winner],`rooms-quick-${['p2','p3'][winner]}`,'changed')).toEqual({ok:false,error:{code:'IDEMPOTENCY_CONFLICT'}});
    const stored=await repository.get('rooms-a');expect(stored.ok&&stored.value.players.length).toBe(2);
    expect(await service.quickMatch('rooms-observer','rooms-empty','empty')).toEqual({ok:true,value:{joined:null,fallback:['browse','create']}});
    expect((await service.create(command('rooms-c','p1','rooms-create-c'),25,true)).ok).toBe(true);
    const sameRoom=await Promise.all(['p2','p3'].map(actor=>service.quickMatch(actor,`rooms-large-${actor}`,'large')));
    expect(sameRoom.map(result=>result.ok&&result.value.joined)).toEqual(['rooms-c','rooms-c']);
    const current=await repository.get('rooms-c');expect(current.ok&&current.value.players.length).toBe(3);
  });
});
